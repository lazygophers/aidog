// 生成 flutter/lib/src/utils/pinyin_data.dart —— Flutter 侧拼音搜索的自建小型词典。
//
// 数据源（全部一次取定、入库为数据文件，产物确定性）：
//   字表：scripts/pinyin_3500.txt（《现代汉语常用字表》3500 常用字，3500 个去重 CJK 字符）。
//   读音：pinyin-pro（3.28.x，仓库既有依赖）的单字最常用读音，toneType:'none'；
//         首字母取该读音第一个字母。
//
// 不引 pub.dev 拼音包的理由：唯一候选包多年未更新且许可证未核实（AGPL 仓库不引），
// 见 flutter/README.md 拼音搜索一节。
//
// 用法：
//   node scripts/gen-flutter-pinyin-data.mjs           # 生成（覆盖写）
//   node scripts/gen-flutter-pinyin-data.mjs --check   # 与现有文件逐字节比对（门禁用）

import { pinyin } from "pinyin-pro";
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "flutter", "lib", "src", "utils", "pinyin_data.dart");
const LIST = join(HERE, "pinyin_3500.txt");

const raw = readFileSync(LIST, "utf8");
const chars = [...new Set([...raw].filter((c) => c >= "一" && c <= "鿿"))];
if (chars.length !== 3500) {
  console.error(`pinyin_3500.txt 应有 3500 个 CJK 字符，实际 ${chars.length}`);
  process.exit(1);
}

const full = [];
const initials = [];
for (const ch of chars) {
  const py = pinyin(ch, { toneType: "none" });
  if (py === ch) {
    console.error(`pinyin-pro 无 ${ch} 的读音，请换字表或补数据`);
    process.exit(1);
  }
  full.push(py);
  initials.push(py[0]);
}

const dart = `// GENERATED by scripts/gen-flutter-pinyin-data.mjs —— 禁手改。
// 字表：《现代汉语常用字表》3500 常用字；读音：pinyin-pro 单字最常用读音（无声调）。
// 三个平行字符串按对齐：第 i 个字符的读音 = kPinyinFull.split(' ')[i]、
// 首字母 = kPinyinInitials[i]。重生成：node scripts/gen-flutter-pinyin-data.mjs。

const String kPinyinChars = '${chars.join("")}';

const String kPinyinFull = '${full.join(" ")}';

const String kPinyinInitials = '${initials.join("")}';
`;

if (process.argv.includes("--check")) {
  const cur = readFileSync(OUT, "utf8");
  if (cur !== dart) {
    console.error("pinyin_data.dart 与脚本产物不一致，跑 node scripts/gen-flutter-pinyin-data.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, dart);
}
